"""Compose outlined click lettering; no runtime font request is needed.

Chinese outlines: Ma Shan Zheng, SIL OFL 1.1 (assets/fonts/OFL-MaShanZheng.txt).
The plus, numeral, flourish and composition are drawn for this feedback mark.
"""
from pathlib import Path
import json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen

root = Path(__file__).resolve().parent.parent
font = TTFont(root / 'assets/fonts/niulai-brush.ttf')
glyphs = font.getGlyphSet()
paths = []
for character, x, baseline in [('牛', 0, 67), ('气', 70, 64)]:
    pen = SVGPathPen(glyphs)
    glyphs[font.getBestCmap()[ord(character)]].draw(pen)
    paths.append(f'<path transform="translate({x} {baseline}) scale(.074 -.074)" d="{pen.getCommands()}"/>')

svg = '<svg class="rise-lettering" viewBox="0 0 226 92" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg">'
svg += '<g fill="currentColor" stroke="none">' + ''.join(paths)
svg += '<path d="M153 40 165 39 166 27 172 26 171 38 182 38 181 44 170 44 169 55 163 56 164 45 153 46Z"/>'
svg += '<path d="M188 28Q200 21 205 10L215 12Q210 39 207 61L222 60 220 67Q202 68 188 73L190 66 199 64 204 25 193 32Z"/>'
svg += '<path opacity=".28" d="M17 82Q76 75 148 72 113 80 59 84L11 88 17 82Z"/>'
svg += '</g></svg>'
output = '// Chinese outlines: Ma Shan Zheng (SIL OFL 1.1); see assets/fonts/OFL-MaShanZheng.txt.\n'
output += '// Custom plus, numeral, brush flourish and composition. Generated by scripts/build-rise-lettering.py.\n'
output += 'export const RISE_LETTERING = ' + json.dumps(svg, ensure_ascii=False) + ';\n'
(root / 'rise-lettering.mjs').write_text(output, encoding='utf-8')
print('Outlined feedback lettering generated.')
